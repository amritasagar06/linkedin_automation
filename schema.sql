-- Run once in Supabase Dashboard > SQL Editor > New query.
create extension if not exists pgcrypto;

create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  sequence_no integer not null unique,
  topic text not null,
  question text not null
);

create table if not exists public.style_examples (
  id uuid primary key default gen_random_uuid(),
  body text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.posts (
  id uuid primary key default gen_random_uuid(),
  scheduled_date date not null unique,
  question_id bigint references public.questions(id),
  question text not null,
  title text not null,
  article text not null,
  linkedin_text text not null,
  substack_url text not null default '',
  status text not null default 'pending_substack',
  approval_hash text not null default '',
  linkedin_post_urn text not null default '',
  error_message text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.app_settings (
  name text primary key,
  value text not null default ''
);

create table if not exists public.oauth_states (
  state text primary key,
  created_at timestamptz not null default now()
);

create table if not exists public.private_values (
  name text primary key,
  encrypted_value text not null,
  updated_at timestamptz not null default now()
);

-- The app uses the service-role key only on the server and in GitHub Actions.
-- Keep RLS on; never put the service-role key in browser/client code or GitHub source.
alter table public.questions enable row level security;
alter table public.style_examples enable row level security;
alter table public.posts enable row level security;
alter table public.app_settings enable row level security;
alter table public.oauth_states enable row level security;
alter table public.private_values enable row level security;
